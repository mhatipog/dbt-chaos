"""Regenerate the dbt-chaos commerce dataset: a clean baseline and two faults, each with a control.

    uv run generate.py            # writes data/, missing_dimension.model2data.yml, manifest.json
    uv run generate.py --check    # regenerates into a temporary folder and compares every byte
    uv run generate.py --zip OUT  # also writes the zip of data/, manifest.json and README.md

Every step is deterministic: model2data runs with a fixed seed and anchor day, and the
changes made after it either follow fixed rules or draw from random.Random(SEED).
"""

from __future__ import annotations

import argparse
import copy
import csv
import filecmp
import hashlib
import io
import json
import random
import shutil
import subprocess
import sys
import tempfile
import zipfile
from collections import Counter, defaultdict
from importlib.metadata import version
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SEED = 20261119
AS_OF = "2026-10-31"
ROWS = {"customers": 200, "orders": 2000, "payments": 4000}
ORPHAN_ORDERS = 5
DUPLICATED_CUSTOMERS = 3

# The column order of dbt_chaos/commerce_runner.py COLUMNS.
COLUMNS = {
    "customers": ("row_id", "customer_id", "version", "segment"),
    "orders": (
        "row_id",
        "order_id",
        "customer_id",
        "version",
        "order_day",
        "gross_cents",
        "status",
        "currency",
    ),
    "payments": ("row_id", "payment_id", "order_id", "version", "kind", "amount_cents"),
}
KEYS = {"customers": "customer_id", "orders": "order_id", "payments": "payment_id"}
INTS = {"row_id", "customer_id", "order_id", "payment_id", "version", "gross_cents", "amount_cents"}

Table = list[dict]
Data = dict[str, Table]


# --------------------------------------------------------------------------- model2data
def model2data(model: Path, workdir: Path, name: str) -> tuple[Data, dict | None]:
    """Run the model2data CLI on a model and read back its three seed CSVs."""
    cli = Path(sys.executable).with_name("model2data")
    command = [
        str(cli),
        "generate",
        "--file",
        str(model),
        "--name",
        name,
        "--seed",
        str(SEED),
        "--as-of",
        AS_OF,
    ]
    for table, rows in ROWS.items():
        command += ["--rows-for", f"{table}={rows}"]
    subprocess.run(command, cwd=workdir, check=True, capture_output=True, text=True)
    project = workdir / f"dbt_{name}"
    data = {t: read_csv(project / "seeds" / "raw" / f"{t}.csv") for t in COLUMNS}
    report = project / "defects_report.json"
    return data, json.loads(report.read_text()) if report.exists() else None


def missing_dimension_model(workdir: Path) -> Path:
    """schema.dbml as a model2data document, with orphan customer keys planted on orders."""
    converted = workdir / "converted.model2data.yml"
    cli = Path(sys.executable).with_name("model2data")
    subprocess.run(
        [str(cli), "convert", str(HERE / "schema.dbml"), "-o", str(converted)],
        check=True,
        capture_output=True,
        text=True,
    )
    document = yaml.safe_load(converted.read_text())
    document["model2data"] = "0.3.0"
    document["tables"]["orders"]["defects"] = [
        {"type": "orphan_foreign_keys", "column": "customer_id", "count": ORPHAN_ORDERS}
    ]
    out = workdir / "missing_dimension.model2data.yml"
    out.write_text(
        "# Generated by generate.py from schema.dbml: the same model, plus one defect.\n"
        + yaml.safe_dump(document, sort_keys=False)
    )
    return out


# --------------------------------------------------------------------------- csv
def read_csv(path: Path) -> Table:
    with path.open(newline="") as handle:
        return [
            {k: int(v) if k in INTS else v for k, v in row.items()}
            for row in csv.DictReader(handle)
        ]


def csv_bytes(table: str, rows: Table) -> bytes:
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=COLUMNS[table], lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return buffer.getvalue().encode()


# --------------------------------------------------------------------------- contract alignment
def align_payments(orders: Table, payments: Table) -> tuple[Table, dict]:
    """Make each payment agree with its order, which model2data cannot do across tables.

    For each order, its payments in payment_id order:
    1. a cancelled order keeps none (cancelled before payment was taken);
    2. on a completed order the first payment is the capture of the order's gross_cents;
    3. the first later payment model2data drew as a refund stays a refund, of
       min(amount_cents, gross_cents), so no order nets below zero;
    4. every other payment is dropped: one capture and at most one refund per order.
    """
    by_order = {o["order_id"]: o for o in orders}
    grouped: dict[int, Table] = defaultdict(list)
    for payment in sorted(payments, key=lambda p: p["payment_id"]):
        grouped[payment["order_id"]].append(payment)
    kept: Table = []
    dropped = Counter()
    for order_id, rows in grouped.items():
        order = by_order[order_id]
        if order["status"] == "cancelled":
            dropped["on_cancelled_order"] += len(rows)
            continue
        capture = dict(rows[0], kind="capture", amount_cents=order["gross_cents"])
        kept.append(capture)
        refund = next((r for r in rows[1:] if r["kind"] == "refund"), None)
        if refund is not None:
            kept.append(
                dict(refund, amount_cents=min(refund["amount_cents"], order["gross_cents"]))
            )
        dropped["extra_payment"] += len(rows) - 1 - (refund is not None)
    kept.sort(key=lambda p: p["payment_id"])
    summary = {"generated": len(payments), "kept": len(kept), "dropped": dict(dropped)}
    return kept, summary


# --------------------------------------------------------------------------- variants
def planted_orphans(clean: Data, broken: Data) -> list[dict]:
    """The orders whose customer_id model2data's defect changed, and nothing else."""
    for table in ("customers", "payments"):
        assert broken[table] == clean[table], f"the defect run changed {table}"
    changes = []
    for before, after in zip(clean["orders"], broken["orders"], strict=True):
        differing = {k for k in before if before[k] != after[k]}
        assert differing <= {"customer_id"}, f"defect changed {differing}"
        if differing:
            changes.append(
                {
                    "table": "orders",
                    "key": {"order_id": before["order_id"]},
                    "column": "customer_id",
                    "from": before["customer_id"],
                    "to": after["customer_id"],
                }
            )
    assert len(changes) == ORPHAN_ORDERS, changes
    return changes


def missing_dimension_control(baseline: Data, orphans: list[dict]) -> tuple[Data, list[dict]]:
    """The same orders re-pointed to another existing customer of the same segment."""
    data = copy.deepcopy(baseline)
    segment = {c["customer_id"]: c["segment"] for c in data["customers"]}
    by_segment: dict[str, list[int]] = defaultdict(list)
    for customer_id in sorted(segment):
        by_segment[segment[customer_id]].append(customer_id)
    rng = random.Random(f"{SEED}:missing_dimension:control")
    changes = []
    for change in orphans:
        order = next(o for o in data["orders"] if o["order_id"] == change["key"]["order_id"])
        candidates = [
            c for c in by_segment[segment[order["customer_id"]]] if c != order["customer_id"]
        ]
        new = rng.choice(candidates)
        changes.append({**change, "to": new, "segment": segment[new]})
        order["customer_id"] = new
    return data, changes


def duplicate_join_key(baseline: Data) -> tuple[Data, Data, list[dict], list[dict]]:
    """Fault: an exact repeat of a customer row (same customer_id and version, new row_id).
    Control: the same customers re-delivered as version 2 with an unchanged segment."""
    captured = {p["order_id"] for p in baseline["payments"] if p["kind"] == "capture"}
    revenue_customers = sorted(
        {o["customer_id"] for o in baseline["orders"] if o["order_id"] in captured}
    )
    rng = random.Random(f"{SEED}:duplicate_join_key")
    chosen = sorted(rng.sample(revenue_customers, DUPLICATED_CUSTOMERS))
    next_row_id = max(c["row_id"] for c in baseline["customers"]) + 1
    fault, control = copy.deepcopy(baseline), copy.deepcopy(baseline)
    fault_changes, control_changes = [], []
    for offset, customer_id in enumerate(chosen):
        original = next(c for c in baseline["customers"] if c["customer_id"] == customer_id)
        row_id = next_row_id + offset
        fault["customers"].append(dict(original, row_id=row_id))
        control["customers"].append(dict(original, row_id=row_id, version=2))
        orders = sum(o["customer_id"] == customer_id for o in baseline["orders"])
        for changes, version_ in ((fault_changes, 1), (control_changes, 2)):
            changes.append(
                {
                    "table": "customers",
                    "change": "row_added",
                    "key": {"customer_id": customer_id, "version": version_},
                    "row": dict(original, row_id=row_id, version=version_),
                    "copy_of_row_id": original["row_id"],
                    "orders_of_customer": orders,
                }
            )
    return fault, control, fault_changes, control_changes


# --------------------------------------------------------------------------- checks
def check(
    data: Data,
    allow_orphans: frozenset[int] | set[int] = frozenset(),
    allow_duplicates: frozenset[int] | set[int] = frozenset(),
) -> dict:
    """Primary keys unique (per key and version), row_ids unique, every foreign key resolves,
    except the planted rows named."""
    for table, rows in data.items():
        row_ids = Counter(r["row_id"] for r in rows)
        assert max(row_ids.values()) == 1, f"{table}: repeated row_id"
        keys = Counter((r[KEYS[table]], r["version"]) for r in rows)
        repeated = {k[0] for k, n in keys.items() if n > 1}
        allowed = allow_duplicates if table == "customers" else set()
        assert repeated == set(allowed), f"{table}: repeated keys {repeated}"
    customers = {c["customer_id"] for c in data["customers"]}
    orders = {o["order_id"] for o in data["orders"]}
    orphans = {o["order_id"] for o in data["orders"] if o["customer_id"] not in customers}
    assert orphans == set(allow_orphans), f"orders without customer: {orphans}"
    assert all(p["order_id"] in orders for p in data["payments"]), "payment without order"
    assert all(
        o["currency"] == "EUR"
        and o["status"] in ("completed", "cancelled")
        and o["gross_cents"] > 0
        for o in data["orders"]
    )
    assert all(
        p["kind"] in ("capture", "refund") and p["amount_cents"] >= 0 for p in data["payments"]
    )
    return {
        "primary_keys_unique": not allow_duplicates,
        "foreign_keys_resolve": not allow_orphans,
        "orphan_orders": sorted(allow_orphans),
        "repeated_customer_keys": sorted(allow_duplicates),
    }


# --------------------------------------------------------------------------- build
def build(out: Path) -> None:
    with tempfile.TemporaryDirectory(prefix="dbt-chaos-commerce-") as temp:
        work = Path(temp)
        clean, _ = model2data(HERE / "schema.dbml", work, "commerce")
        model = missing_dimension_model(work)
        broken, report = model2data(model, work, "commerce_missing_dimension")
        shutil.copy(model, out / model.name)

    orphans = planted_orphans(clean, broken)
    payments, alignment = align_payments(clean["orders"], clean["payments"])
    baseline = {**clean, "payments": payments}
    md_fault = {**broken, "payments": payments}
    md_control, md_control_changes = missing_dimension_control(baseline, orphans)
    dj_fault, dj_control, dj_fault_changes, dj_control_changes = duplicate_join_key(baseline)
    orphan_ids = {c["key"]["order_id"] for c in orphans}
    duplicate_ids = {c["key"]["customer_id"] for c in dj_fault_changes}

    variants = {
        "baseline": (baseline, check(baseline), []),
        "missing_dimension/fault": (md_fault, check(md_fault, allow_orphans=orphan_ids), orphans),
        "missing_dimension/control": (md_control, check(md_control), md_control_changes),
        "duplicate_join_key/fault": (
            dj_fault,
            check(dj_fault, allow_duplicates=duplicate_ids),
            dj_fault_changes,
        ),
        "duplicate_join_key/control": (dj_control, check(dj_control), dj_control_changes),
    }

    manifest: dict = {
        "dataset": "dbt-chaos-commerce",
        "model2data_version": version("model2data"),
        "seed": SEED,
        "as_of": AS_OF,
        "rows_requested": ROWS,
        "contract": "dbt-chaos commerce workload (dbt_chaos/commerce_runner.py COLUMNS)",
        "columns": {t: list(c) for t, c in COLUMNS.items()},
        "payment_alignment": alignment,
        "missing_dimension_defect": report,
        "variants": {},
    }
    data_dir = out / "data"
    if data_dir.exists():
        shutil.rmtree(data_dir)
    for name, (data, checks, changes) in variants.items():
        folder = data_dir / name
        folder.mkdir(parents=True)
        files = {}
        for table in COLUMNS:
            payload = csv_bytes(table, data[table])
            (folder / f"{table}.csv").write_bytes(payload)
            files[f"data/{name}/{table}.csv"] = {
                "rows": len(data[table]),
                "sha256": hashlib.sha256(payload).hexdigest(),
            }
        manifest["variants"][name] = {"files": files, "checks": checks, "planted": changes}
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")


def write_zip(source: Path, target: Path) -> None:
    """A zip with fixed timestamps and order, so the same data gives the same bytes."""
    paths = [
        "README.md",
        "manifest.json",
        "run_with_dbt_chaos.py",
        *sorted(str(p.relative_to(source)) for p in (source / "data").rglob("*.csv")),
    ]
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
        for relative in paths:
            info = zipfile.ZipInfo(f"dbt-chaos-commerce/{relative}", (2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, (source / relative).read_bytes())


def main() -> None:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate into a temporary folder and compare with the files here",
    )
    parser.add_argument("--zip", type=Path, help="also write the zip to send to this path")
    args = parser.parse_args()
    if args.check:
        with tempfile.TemporaryDirectory() as temp:
            build(Path(temp))
            outputs = [
                "manifest.json",
                "missing_dimension.model2data.yml",
                *(str(p.relative_to(HERE)) for p in sorted((HERE / "data").rglob("*.csv"))),
            ]
            _, mismatch, errors = filecmp.cmpfiles(HERE, temp, outputs, shallow=False)
            if mismatch or errors:
                sys.exit(f"differs from a fresh run: {mismatch + errors}")
            print(f"{len(outputs)} files identical to a fresh run")
        return
    build(HERE)
    if args.zip:
        write_zip(HERE, args.zip)
        print(f"wrote {args.zip}")
    print("wrote data/, manifest.json and missing_dimension.model2data.yml")


if __name__ == "__main__":
    main()
