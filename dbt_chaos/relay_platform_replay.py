"""Replay fully archived weak-LLM handoff outcomes through real native dbt controls.

This consumes verified corpus snapshots generated by a PREVIOUS run. No LLM
is run here, so outcomes are not cherry-picked or changed by regeneration.
The entire authoritative event ledger is used only in the independent scorer.
Native warehouse SQL sees the delivered source snapshot exclusively.
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
from typing import Any

from .audit_corpus import audit_corpus, read_gold, read_tables
from .commerce import CommerceCase
from .commerce_runner import run_case
from .full_datasets import enhanced_source_alerts
from .relay_diagnostics import analyse


def score_publication(truth: dict[tuple[str, str], int],
                      published: dict[tuple[str, str], int],
                      held: set[tuple[str, str]]) -> dict[str, Any]:
    """Differentiate withheld truth from silently missing or wrong publication."""
    actual_keys = set(published)
    true_keys = set(truth)
    false_published = sorted(k for k in actual_keys
                             if published[k] != truth.get(k, 0))
    silent_omitted = sorted(k for k in true_keys - actual_keys if k not in held)
    if actual_keys & held:
        raise ValueError("publication contains deliberately withheld groups")
    correctly_published = [
        k for k in actual_keys & true_keys if published[k] == truth[k]
    ]
    denom = sum(abs(value) for value in truth.values())
    value_preserved = (
        sum(abs(truth[k]) for k in correctly_published) / denom if denom else 1.0
    )
    return {
        "false_published_groups": [f"{d}|{s}" for d,s in false_published],
        "silent_missing_groups": [f"{d}|{s}" for d,s in silent_omitted],
        "held_groups": [f"{d}|{s}" for d,s in sorted(held)],
        "correct_published_groups": len(correctly_published),
        "published_groups": len(actual_keys),
        "fraction_of_correct_business_value_published": round(value_preserved, 6),
        "false_published_l1_cents": sum(
            abs(published[k] - truth.get(k, 0)) for k in false_published),
        "unannounced_missing_l1_cents": sum(
            abs(truth[k]) for k in silent_omitted),
        "status": (
            "silently_wrong" if false_published or silent_omitted
            else "held" if held and not published
            else "partially_held" if held
            else "correctly_published"
        ),
    }


def replay_archived_corpus(root: Path, *, seed: int,
                           source_run_id: int) -> dict:
    if source_run_id <= 0:
        raise ValueError("source run id must be positive")
    # Validate complete longitudinal chain and its matched controls first.
    diagnostic = analyse(root)
    if diagnostic["seed"] != seed:
        raise ValueError("artifact seed mismatch")
    modes = list(diagnostic["arms"])
    results = []
    for mode in modes:
        path = root / mode
        verified = audit_corpus(path)
        trace = json.loads((path / "trace.json").read_text())
        final_step = trace["steps"][-1]
        if final_step["evidence_level"] != "executed_dbt_duckdb":
            raise ValueError("final step must have real dbt baseline output")
        truth = read_tables(path, "ledger/source_of_truth")
        delivered = read_tables(
            path, f"steps/{final_step['step']:02d}/source_delivery")
        truth_gold = read_gold(path, "ledger/business_gold.csv")
        baseline_gold = read_gold(
            path, f"steps/{final_step['step']:02d}/dbt_gold.csv")
        original = score_publication(truth_gold, baseline_gold, set())
        # Native quality models, actual DBT/DuckDB. The process ledger
        # enters the independent assessment AFTER SQL execution only.
        native = run_case(
            CommerceCase(logic_fault=final_step["logic_fault"]),
            admitted_data=delivered, process_data=truth,
            quality_enabled=True,
        )
        reported = native["native_quality"]
        publish = {
            tuple(k.split("|", 1)): int(v)
            for k, v in reported["released_gold"].items()
        }
        held = {
            tuple(k.split("|", 1)) for k in reported["held_groups"]
        }
        if reported["release_status"] == "withheld_all":
            held |= set(truth_gold)
        native_scored = score_publication(truth_gold, publish, held)
        results.append({
            "mode": mode, "seed": seed,
            "verified_archived_snapshots": verified["snapshots"],
            "final_step": final_step["step"],
            "model_sha256": trace["model_sha256"],
            "original_dbt_source_alerts": final_step["dbt_source_alerts"],
            "original_dbt_output_alerts": final_step["dbt_output_alerts"],
            "observable_enhanced_alerts": enhanced_source_alerts(delivered),
            "base_dbt": original,
            "native_dbt": native_scored,
            "native_release_status": reported["release_status"],
            "native_quarantine_count": reported["quarantined_row_count"],
            "native_quarantine_reasons": dict(Counter(
                row["reason"] for row in reported["quarantine"]
            )),
            "native_actual_sql_executed": reported["models_executed_by_dbt"],
            "evidence_tier": "delivered_snapshot_only_for_native_policy",
        })
    return {
        "experiment": "real_native_dbt_on_frozen_llm_20_handoffs_v1",
        "source_llm_workflow_run_id": source_run_id,
        "seed": seed, "context_conditions": modes,
        "results": results,
        "independently_verified_full_corpus": True,
        "warning": (
            "Ledger used for outcome scoring, NOT the native dbt protection "
            "models. Baseline and native gold must be compared only using "
            "what was actually published; no implied repair."
        ),
    }


def main() -> None:
    ap = argparse.ArgumentParser(description="Run native dbt on frozen 20-step LLM corpora")
    ap.add_argument("--corpus", type=Path, required=True)
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--source-run-id", type=int, required=True)
    ap.add_argument("--output", type=Path, required=True)
    args = ap.parse_args()
    data = replay_archived_corpus(
        args.corpus, seed=args.seed, source_run_id=args.source_run_id)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(data, sort_keys=True, indent=2) + "\n")
    print(json.dumps([
        {
            "mode": r["mode"], "baseline": r["base_dbt"]["status"],
            "native": r["native_dbt"]["status"],
            "native_quarantined": r["native_quarantine_count"],
            "baseline_false_groups": len(r["base_dbt"]["false_published_groups"]),
            "native_false_groups": len(r["native_dbt"]["false_published_groups"]),
            "native_value_preserved":
                r["native_dbt"]["fraction_of_correct_business_value_published"],
        }
        for r in data["results"]
    ], indent=2))


if __name__ == "__main__":
    main()
